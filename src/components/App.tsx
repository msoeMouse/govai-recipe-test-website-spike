const App = () => {
    //Created with CoPilot on 9-15-2026
    /**
     * When the button is pressed, take the text in the user textbox and feed it to
     * GovAI. If you can query, return that response and put it in the next textbox
     */
    async function askAI() {
        //help with copilot
        let input = document.getElementById("userInput") as HTMLInputElement | null;
        let responseElement = document.getElementById("aiResponse");
        
        if (!input || !responseElement) return;
        
        const text = input.value.trim();

        if (!text) {
            responseElement.textContent = "Please enter a question!";
            return;
        }

        try {
            const response = await fetch("http://localhost:3001/api/ask", {
                method: "POST",
                headers: {
                    "Content-Type": "application/json",
                },
                body: JSON.stringify({ question: text }),
            });
            const data: { answer?: string; error?: string } = await response.json();

            if (!response.ok) {
                throw new Error(data.error || "The AI service could not complete the request.");
            }

            if (!data.answer) {
                throw new Error("The AI service returned an empty response.");
            }

            responseElement.textContent = data.answer;
        } catch (err) {
            console.log(err);
            responseElement.textContent = "Error occurred! " + (err instanceof Error ? err.message : String(err));
        }
    }

    return (
        <>
            <h1>Welcome to the GovAi Test Website!</h1>
            <p>Ask the AI to help you with a question in the left box!</p>
            <table>
                <tbody>
                <tr>
                    <td>
                    <input type="text" id="userInput" placeholder="Ask a question..."/>
                    </td>
                    <td>
                    <p id="aiResponse">Type a question in the box next to me...</p>
                    </td>
                </tr>
                </tbody>
            </table>
            <button name="askAI" onClick={askAI}>
                Ask GovAI!
            </button>
            <p>*Responses are generated by artificial intelligence and may contain errors.</p>
        </>
    );
};

export default App;